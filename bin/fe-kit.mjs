function enableClaudePlugin(target) {
  const file = path.join(target, '.claude', 'settings.json');
  let settings = {};
  if (fs.existsSync(file)) {
    try {
      settings = JSON.parse(fs.readFileSync(file, 'utf8'));
    } catch {
      console.warn(`Không parse được ${file}; hãy tự thêm enabledPlugins["${PLUGIN_ID}"] = true.`);
      return false;
    }
  }
  const repo = marketplaceRepo();
  settings.extraKnownMarketplaces ||= {};
  if (!settings.extraKnownMarketplaces[MARKETPLACE_NAME] && repo) {
    settings.extraKnownMarketplaces[MARKETPLACE_NAME] = { source: { source: 'github', repo } };
  }
  settings.enabledPlugins ||= {};
  settings.enabledPlugins[PLUGIN_ID] = true;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(settings, null, 2) + '\n');
  return true;
}

