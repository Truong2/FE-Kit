function leanModeOutputErrors(taskDir) {
  const workflowPath = path.join(taskDir, 'tracking', 'workflow-status.md');
  if (!exists(workflowPath)) return ['Thiếu tracking/workflow-status.md'];

  const raw = read(workflowPath);
  const parsed = parseWorkflowStatus(raw);
  if (!parsed.ok) return parsed.errors;

  const existsRel = (rel) => exists(path.join(taskDir, rel));
  const readRel = (rel) => read(path.join(taskDir, rel));

  const result = evaluateWorkflowGates({
    data: parsed.data,
    body: parsed.body,
    exists: existsRel,
    read: readRel,
  });
  return result.errors;
}
