function newTask() {
  const slug = args[1];
  if (!slug) {
    console.error('Usage: node bin/fe-kit.mjs new-task FE-123-task-name [--target repo]');
    process.exit(1);
  }
  if (args.includes('--layout')) {
    console.error('Không còn hỗ trợ --layout. new-task luôn dùng standard task structure.');
    process.exit(1);
  }
  const target = path.resolve(argValue('--target', process.cwd()));
  const taskDir = path.join(target, 'docs', 'frontend-tasks', slug);
  fs.mkdirSync(path.join(taskDir, 'planning'), { recursive: true });
  fs.mkdirSync(path.join(taskDir, 'tracking'), { recursive: true });
  fs.mkdirSync(path.join(taskDir, 'output', 'figma-reference-screenshots'), { recursive: true });

  // Path ghi vào artifact luôn dùng dấu `/`: trên Windows `path.relative` trả
  // về `docs\frontend-tasks\...`, và khi chèn vào scalar YAML nháy kép
  // (`next_prompt: "FE plan <task-folder>"`) thì `\f` là escape sequence không
  // hợp lệ => validate-workflow không parse được frontmatter.
  const taskRel = toPosix(path.relative(target, taskDir) || taskDir);
  const replacements = (txt) => txt.replaceAll('<task-folder>', taskRel).replaceAll('<task-id>', slug).replaceAll('<TASK_ID>', slug);
  const files = [
    ['task.md', 'task.md'],
    [path.join('planning', 'implementation-plan.md'), path.join('planning', 'implementation-plan.md')],
    [path.join('planning', 'build-checklist.md'), path.join('planning', 'build-checklist.md')],
    [path.join('planning', 'questions.md'), path.join('planning', 'questions.md')],
    [path.join('tracking', 'workflow-status.md'), path.join('tracking', 'workflow-status.md')]
  ];
  for (const [destRel, templateRel] of files) {
    const dest = path.join(taskDir, destRel);
    if (!fs.existsSync(dest)) {
      const template = readTemplate(kitTemplate(templateRel));
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.writeFileSync(dest, replacements(template || ''));
    }
  }
  const gitkeep = path.join(taskDir, 'output', 'figma-reference-screenshots', '.gitkeep');
  if (!fs.existsSync(gitkeep)) fs.writeFileSync(gitkeep, '');
  console.log(`Created task: ${taskDir}`);
  console.log('Created standard task files: task.md, planning/implementation-plan.md, planning/build-checklist.md, planning/questions.md, tracking/workflow-status.md, output/figma-reference-screenshots/.gitkeep');

  // Đọc next_prompt thật từ workflow-status.md vừa ghi, không hardcode —
  // tránh lệch nếu default template thay đổi sau này.
  const workflowText = read(path.join(taskDir, 'tracking', 'workflow-status.md'));
  const realNextPrompt = extractNextPrompt(workflowText);
  console.log(`\nTiếp theo: ${realNextPrompt || `FE plan ${taskRel}`}`);
  console.log('Nếu SRS có req/res/DTO/error context thì SRS là source of truth cho API.');
  console.log(`Task nhỏ, rủi ro thấp, không cần re-plan/input-sync/Figma? Dùng thay: FE quick ${taskRel}`);
  console.log(`Workflow status: ${path.join(taskDir, 'tracking', 'workflow-status.md')}`);
}

