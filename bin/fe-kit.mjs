function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

function resolveTask(input, target = process.cwd()) {
  if (!input) return '';
  const direct = path.resolve(input);
  if (fs.existsSync(direct)) return direct;
  const fromTarget = path.resolve(target, input);
  if (fs.existsSync(fromTarget)) return fromTarget;
  return path.resolve(target, 'docs', 'frontend-tasks', input);
}

function section(text, heading) {
  const escaped = heading.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const re = new RegExp(`^##\\s+${escaped}[\\t ]*\\n[\\s\\S]*?(?=\\n##\\s+|(?![\\s\\S]))`, 'm');
  const m = text.match(re);
  return m ? m[0].trim() : '';
}

