function validatePrLean() {
  const target = path.resolve(argValue('--target', process.cwd()));
  const taskDir = resolveTask(taskArg(), target);
  if (!taskDir || !exists(taskDir)) { console.error('Task folder not found.'); process.exit(1); }
  let ok = true;
  const errs = leanModeOutputErrors(taskDir);
  if (errs.length) { ok = false; for (const e of errs) console.error(e); }
  for (const rel of ['output/review-report.md','output/test-summary.md','output/pr-summary.md','tracking/workflow-status.md']) {
    const present = exists(path.join(taskDir, rel));
    console.log(`${present ? 'OK' : 'MISSING'} ${rel}`);
    if (!present) ok = false;
  }
  const fm = parseFrontMatter(read(path.join(taskDir, 'tracking', 'workflow-status.md')));
  const data = fm.data || {};
  if (!['passed','not_required'].includes(normValue(data.review_status))) { ok = false; console.error('review_status phải passed/not_required trước PR.'); }
  if (boolValue(data.bugfix_required) || Number(data.critical_issues_open || 0) > 0 || Number(data.high_issues_open || 0) > 0 || ['open','blocked'].includes(normValue(data.review_bug_status))) { ok = false; console.error('Còn review bug/Critical/High trước PR.'); }
  if (!['passed','not_required'].includes(normValue(data.scope_diff_status))) { ok = false; console.error('scope_diff_status phải passed/not_required trước PR.'); }
  if (!['completed','not_required'].includes(normValue(data.command_evidence_status))) { ok = false; console.error('command_evidence_status phải completed/not_required trước PR.'); }
  if (!['completed','not_required'].includes(normValue(data.test_command_log_status))) { ok = false; console.error('test_command_log_status phải completed/not_required trước PR.'); }
  if (boolValue(data.figma_required) && !['passed','waived','not_required'].includes(normValue(data.ui_match_review_status))) { ok = false; console.error('Task UI/Figma cần ui_match_review_status=passed/waived/not_required trước PR.'); }
  if (boolValue(data.figma_required) && !['passed','manual_review','not_required','waived'].includes(normValue(data.playwright_screenshot_diff_status))) { ok = false; console.error('Task UI/Figma cần playwright_screenshot_diff_status=passed/manual_review/not_required/waived trước PR.'); }
  if (!['ready','opened','merged'].includes(normValue(data.pr_status))) { ok = false; console.error('pr_status phải ready/opened/merged trước PR validation.'); }
  if (!ok) process.exit(1);
  console.log('validate-pr passed.');
  console.log(nextStepHint(taskDir));
}

